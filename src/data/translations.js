// Safe translation accessor that guarantees fallback to English if key or language is missing
export function getTranslation(lang) {
  const target = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;
  return new Proxy(target, {
    get(obj, prop) {
      if (prop in obj && obj[prop] !== undefined) {
        return obj[prop];
      }
      return UI_TRANSLATIONS.en[prop] || '';
    }
  });
}
